export const LANGS = { es: "Español", en: "English" };
const pick = (l) => (l in STR ? l : null);
let lang = "es";
export const getLang = () => lang;
// Idioma guardado, o el del navegador: español si empieza con "es", si no inglés.
export function initLang(saved) { lang = pick(saved) || (/^es\b/i.test(navigator.language || "") ? "es" : "en"); return lang; }
export function setLang(l) { lang = pick(l) || lang; }
export function t(key, vars = {}) {
  const s = STR[lang][key] ?? STR.es[key] ?? key;
  return typeof s === "string" ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "") : s;
}
// Pone los textos del idioma actual en todo lo marcado con data-t, data-t-aria y data-t-ph.
export function applyLang(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-t]")) el.textContent = t(el.dataset.t);
  for (const el of root.querySelectorAll("[data-t-aria]")) el.setAttribute("aria-label", t(el.dataset.tAria));
  for (const el of root.querySelectorAll("[data-t-ph]")) el.placeholder = t(el.dataset.tPh);
}
